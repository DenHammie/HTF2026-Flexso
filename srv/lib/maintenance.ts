const SIGNATURE = 'The Winter is Coming';

const HINT = 'The sigil reads better in plain text: ?format=text';

interface Payload {
  readonly message: string;
  readonly logo: string;
  readonly signature: string;
  readonly hint: string;
}

interface FoundEnvelope {
  readonly status: 'found';
  readonly data: Payload;
  readonly errors: readonly string[];
  readonly timestamp: string;
}

function wantsPlainText(req: Request): boolean {
  return req.query.format === 'text' || (req.headers.accept ?? '').includes('text/plain');
}

/** Registers the maintenance route on the given Express app. */
export function registerMaintenanceRoutes(app: ExpressApp): void {
  const route = '/' + ['reveal', 'if', 'you', 'dare'].join('_');

  app.get(route, (req, res) => {
    if (wantsPlainText(req)) {
      res.type('text/plain; charset=utf-8').send([MESSAGE, '', LOGO, '', SIGNATURE].join('\n'));
      return;
    }

    const body: FoundEnvelope = {
      status: 'found',
      data: { message: MESSAGE, logo: LOGO, signature: SIGNATURE, hint: HINT },
      errors: [],
      timestamp: new Date().toISOString()
    };
    res.json(body);
  });
}
